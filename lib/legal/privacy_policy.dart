• احتساب العمولة وإدارة المحفظة واعتماد عمليات الشحن
• دعم العملاء ومعالجة الشكاوى والنزاعات
• تحسين جودة الخدمة، الأمان، ومنع الاحتيال أو إساءة الاستخدام
• الالتزام بالمتطلبات القانونية عند الاقتضاء
• عرض محتوى الهوية والدعم داخل التطبيق (مثل اسم التطبيق ووسائل التواصل)

