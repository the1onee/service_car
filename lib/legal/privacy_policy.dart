التطبيق موجّه لخدمات سيارات للمستخدمين البالغين القادرين على التعاقد. لا نستهدف جمع بيانات من الأطفال عن قصد. إذا علمت بأن طفلاً قدّم بيانات دون موافقة مناسبة، تواصل معنا لحذفها عند الإمكان.

9. روابط وخدمات خارجية
