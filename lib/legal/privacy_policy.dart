• ملاحظة: الدفع النقدي بين العميل ومقدّم الخدمة يتم خارج بوابات دفع إلكترونية تابعة للتطبيق؛ لا نجمع بيانات بطاقات بنكية عبر التطبيق لهذا الغرض

د) بيانات الجهاز والإشعارات
• رمز إشعارات الدفع (FCM token) لإرسال تنبيهات الطلبات والحساب
