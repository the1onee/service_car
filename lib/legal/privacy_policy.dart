• مقدّمي الخدمة المرتبطين بطلبك (مثل الاسم/الهاتف/الموقع/تفاصيل الطلب) لتنفيذ الخدمة والتواصل
• مزوّدي البنية التحتية التقنية الذين نعتمد عليهم لتشغيل المنصة، ومنها على سبيل المثال:
  – Firebase (المصادقة وقاعدة البيانات والإشعارات)
  – خدمات رفع الصور (مثل Cloudinary) عند رفعك لصور
  – خادم الإشعارات/الإدارة المرتبط بنطاق التطبيق
• جهات إنفاذ القانون أو الجهات المختصة إذا طُلب ذلك بموجب قانون سارٍ أو لحماية الحقوق والسلامة

يُطلب من مقدّمي الخدمات الالتزام بعدم إساءة استخدام بيانات العملاء التي تصلهم عبر المنصة، وفق شروط استخدام كل دور.

5. الاحتفاظ بالبيانات
نحتفظ بالبيانات طالما كان الحساب نشطاً أو طالما كان الاحتفاظ لازماً لتقديم الخدمة، أو لإثبات المعاملات، أو للامتثال القانوني، أو لفض النزاعات.
عند طلب حذف الحساب أو إيقافه، قد نحتفظ بحد أدنى من السجلات اللازمة للالتزامات القانونية والمالية ومنع إساءة الاستخدام، وفق ما يسمح به القانون.

6. حقوقك وخياراتك
بحسب القوانين المعمول بها وإمكانات المنصة، يمكنك:
• الاطلاع على بيانات ملفك وتحديث الاسم والهاتف والعنوان والصور من داخل التطبيق
• إدارة أذونات الموقع والإشعارات من إعدادات جهازك
• التواصل معنا لطلب تصحيح بيانات أو الاستفسار عن المعالجة أو طلب حذف الحساب عند الإمكان
• إيقاف استخدام التطبيق في أي وقت

لطلبات الخصوصية أو حذف البيانات: تواصل عبر ${AppBrand.supportPhone} أو ${AppBrand.supportEmail}.

7. أمان المعلومات
نتخذ إجراءات تقنية وتنظيمية معقولة لحماية البيانات (مثل التحكم في الوصول وقواعد قاعدة البيانات وتقييد الصلاحيات).
