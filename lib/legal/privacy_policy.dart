• رقم الهاتف و/أو البريد الإلكتروني
• العنوان أو منطقة الخدمة
• كلمة المرور (تُعالَج عبر مزوّد المصادقة ولا نخزّنها كنص واضح لدينا)
• صورة الملف الشخصي إن رفعتها
• دور الحساب وحالة التوثيق/الاعتماد عند الاقتضاء

